-- Ephemeral CI fixture only. Never applied to Supabase or production.
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA IF NOT EXISTS governance_layer;
CREATE SCHEMA IF NOT EXISTS staging_enrichment;
CREATE SCHEMA IF NOT EXISTS production_layer;

DO $roles$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    CREATE ROLE anon NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    CREATE ROLE authenticated NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    CREATE ROLE service_role NOLOGIN;
  END IF;
END
$roles$;

CREATE TABLE IF NOT EXISTS governance_layer.master_import_batch (
  batch_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  source_name text NOT NULL,
  source_hash text,
  status text NOT NULL CHECK (status IN ('STAGED', 'AUTHORIZED', 'IMPORTED', 'BLOCKED')),
  owner_authorized_at timestamptz(6),
  created_at timestamptz(6) NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS staging_enrichment.master_4187_staging (
  staging_row_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id uuid,
  name text NOT NULL,
  symbol text NOT NULL,
  exchange text NOT NULL,
  sector text,
  sub_sector text,
  identity_status text NOT NULL DEFAULT 'PENDING',
  created_at timestamptz(6) NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS governance_layer.identity_conflict (
  conflict_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  batch_id uuid,
  exchange text NOT NULL,
  symbol text NOT NULL,
  status text NOT NULL,
  resolution_note text,
  resolved_at timestamptz(6)
);

CREATE TABLE IF NOT EXISTS governance_layer.identity_resolution_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  symbol text NOT NULL,
  conflict_type text NOT NULL,
  evidence_url text,
  proposed_canonical_identity text NOT NULL,
  proposed_isin text,
  impact_on_4187_rows text NOT NULL,
  state text NOT NULL,
  owner_decision text,
  owner_decided_at timestamptz(6),
  owner_note text,
  created_at timestamptz(6) NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS production_layer.canonical_stock (
  stock_id uuid PRIMARY KEY DEFAULT gen_random_uuid()
);

CREATE TABLE IF NOT EXISTS production_layer.raw_stock_observation (
  observation_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  stock_id uuid,
  freshness_status text,
  verification_status text,
  interpretation_status text,
  workflow_status text,
  data_nature text,
  formula_version text,
  formula_version_id uuid,
  configuration_snapshot jsonb
);
